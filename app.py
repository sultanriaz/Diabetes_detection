from flask import Flask, request, jsonify, render_template
import joblib
import numpy as np
import traceback
import os

from symptom_search import integrate_symptom_search
from treatment_recommendation import integrate_treatment_module

app = Flask(__name__)

# -------------------- Paths --------------------
MODELS_DIR = os.path.join("Models")

# -------------------- Load Model & Scaler --------------------
try:
    rf_model = joblib.load(os.path.join(MODELS_DIR, "diabetes_rf.joblib"))
    scaler = joblib.load(os.path.join(MODELS_DIR, "scaler.joblib"))
except Exception as e:
    print(f"Error loading model files: {e}")
    rf_model = None
    scaler = None

# -------------------- Feature Order (MUST match training) --------------------
feature_names = [
    "Pregnancies",
    "Glucose",
    "BloodPressure",
    "SkinThickness",
    "Insulin",
    "BMI",
    "DiabetesPedigreeFunction",
    "Age"
]

# -------------------- Routes --------------------
@app.route("/")
def home():
    return render_template("index.html", feature_names=feature_names)

@app.route("/dashboard")
def dashboard():
    return render_template("dashboard.html", feature_names=feature_names)

@app.route("/about")
def about():
    return render_template("about.html", feature_names=feature_names)

# -------------------- Prediction Endpoint --------------------
@app.route("/predict", methods=["POST"])
def predict():
    try:
        if rf_model is None or scaler is None:
            return jsonify({"error": "Model not loaded. Contact administrator."}), 500

        data = request.get_json()
        if not data:
            return jsonify({"error": "No input data provided"}), 400

        # Check missing features
        missing = [f for f in feature_names if f not in data]
        if missing:
            return jsonify({"error": f"Missing features: {missing}"}), 400

        # Validate numeric inputs
        for feature in feature_names:
            try:
                data[feature] = float(data[feature])
            except (ValueError, TypeError):
                return jsonify({
                    "error": f"Invalid value for {feature}. Must be numeric."
                }), 400

        # Prepare input
        raw_features = np.array([[data[f] for f in feature_names]], dtype=float)
        scaled_features = scaler.transform(raw_features)

        # Model inference
        rf_pred = int(rf_model.predict(scaled_features)[0])
        rf_prob = float(rf_model.predict_proba(scaled_features)[0][1])

        # -------------------- Risk Stratification --------------------
        # NOTE: rf_prob is a MODEL RISK SCORE, not a calibrated probability

        if rf_prob >= 0.80:
            risk_info = {
                "risk_level": "High",
                "recommendations": [
                    "High model-based risk detected.",
                    "Strongly recommend laboratory testing (FPG / HbA1c).",
                    "Consult an endocrinologist or physician promptly."
                ]
            }

        elif rf_prob >= 0.65:
            risk_info = {
                "risk_level": "Moderate",
                "recommendations": [
                    "Moderate model-based risk detected.",
                    "Lifestyle modification is advised (diet and exercise).",
                    "Periodic glucose monitoring is recommended."
                ]
            }

        else:
            risk_info = {
                "risk_level": "Low",
                "recommendations": [
                    "Low model-based risk detected.",
                    "Maintain a healthy lifestyle.",
                    "Routine screening as per clinical guidelines."
                ]
            }

        # -------------------- Response --------------------
        return jsonify({
            "prediction": rf_pred,
            "risk_score": round(rf_prob, 4),
            "risk_level": risk_info["risk_level"],
            "recommendations": risk_info["recommendations"],
            "disclaimer": (
                "This assessment is generated by a machine learning model and "
                "does not constitute a medical diagnosis."
            )
        })

    except Exception as e:
        app.logger.error(f"Prediction error: {str(e)}")
        traceback.print_exc()
        return jsonify({
            "error": "Internal server error during prediction"
        }), 500

# -------------------- App Entry --------------------
if __name__ == "__main__":
    integrate_treatment_module(app)
    integrate_symptom_search(app)
    app.run(host="0.0.0.0", port=5000, debug=True)
